    /// <summary>
    /// The same list keyed by the name with its accents and punctuation taken off, so a country
    /// stored before there was a dropdown -- "Etats-Unis", "etats unis" -- still resolves.
    /// </summary>
    private static readonly Dictionary<string, string> ByNormalizedName =
        ByName.GroupBy(pair => CompanyIdentity.Normalize(pair.Key))
            .ToDictionary(group => group.Key, group => group.First().Value, StringComparer.Ordinal);

    /// <summary>
    /// The code for a stored country name, or null when it is empty or unrecognised.
    ///
    /// Null rather than a guess. Defaulting to Canada would quietly open a Stripe account in the
    /// wrong country for a company that is not here, and a connected account's country cannot be
    /// changed afterwards -- it would have to be abandoned and opened again.
    /// </summary>
    public static string? Of(string? countryName)
    {
        if (string.IsNullOrWhiteSpace(countryName)) return null;

        var trimmed = countryName.Trim();
        if (ByName.TryGetValue(trimmed, out var code)) return code;

        return ByNormalizedName.TryGetValue(CompanyIdentity.Normalize(trimmed), out var fallback)
            ? fallback
            : null;
    }
